#!/usr/bin/env node
/**
 * openapi.json → src/api-types.ts 生成スクリプト（外部パッケージ依存なし）
 *
 * バックエンドの app/schemas.py（Pydantic）が契約の単一情報源。
 *   1. .venv\Scripts\python.exe app\export_openapi.py   （repo root）→ openapi.json
 *   2. npm run gen:api                                  （このスクリプト）→ src/api-types.ts
 *
 * ビルド（npm run build）が自動で実行する。手で書き換えないこと。
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const spec = JSON.parse(readFileSync(join(root, "openapi.json"), "utf8"));
const schemas = spec.components?.schemas ?? {};

const SCALARS = {
  string: "string",
  number: "number",
  integer: "number",
  boolean: "boolean",
  object: "Record<string, unknown>",
  null: "null",
};

function refName(ref) {
  return ref.split("/").pop();
}

function tsType(s) {
  if (!s || typeof s !== "object") return "unknown";
  if (s.$ref) return refName(s.$ref);
  if (Array.isArray(s.enum)) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.anyOf || s.oneOf) {
    return [...new Set((s.anyOf ?? s.oneOf).map(tsType))].join(" | ");
  }
  if (s.type === "array") return `Array<${tsType(s.items)}>`;
  if (Array.isArray(s.type)) return s.type.map((t) => SCALARS[t] ?? "unknown").join(" | ");
  if (s.type) return SCALARS[s.type] ?? "unknown";
  if (s.properties) return inlineObject(s);
  return "unknown";
}

function inlineObject(s) {
  const req = new Set(s.required ?? []);
  const lines = Object.entries(s.properties ?? {}).map(([name, prop]) => {
    const opt = req.has(name) ? "" : "?";
    return `${name}${opt}: ${tsType(prop)};`;
  });
  return `{ ${lines.join(" ")} }`;
}

function docFor(prop) {
  if (!prop.description) return "";
  const text = prop.description.replace(/\*\//g, "*\\/");
  return `  /** ${text} */\n`;
}

function emitInterface(name, schema) {
  const req = new Set(schema.required ?? []);
  const props = Object.entries(schema.properties ?? {}).map(([pname, prop]) => {
    const opt = req.has(pname) ? "" : "?";
    return `${docFor(prop)}  ${pname}${opt}: ${tsType(prop)};`;
  });
  if (schema.additionalProperties === true) {
    props.push("  /** 追加キーも保持される（契約は known フィールドのみ型検証） */\n  [key: string]: unknown;");
  }
  return `export interface ${name} {\n${props.join("\n")}\n}`;
}

const parts = [
  "/**",
  " * GENERATED FILE — do not edit by hand.",
  " * Generated by scripts/gen-api-types.mjs from openapi.json.",
  " * Source of truth: app/schemas.py (Pydantic).",
  " * Regenerate: .venv\\Scripts\\python.exe app\\export_openapi.py && npm run gen:api",
  " */",
  "",
];

for (const name of Object.keys(schemas).sort()) {
  parts.push(emitInterface(name, schemas[name]), "");
}

writeFileSync(join(root, "src", "api-types.ts"), parts.join("\n"), "utf8");
console.log(`wrote src/api-types.ts (${Object.keys(schemas).length} schemas)`);
